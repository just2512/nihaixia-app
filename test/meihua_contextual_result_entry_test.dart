import 'dart:math';

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:sensors_plus/sensors_plus.dart';

import 'package:nihaisha_app/models/ai_context_ref.dart';
import 'package:nihaisha_app/models/assistant_tool_result.dart';
import 'package:nihaisha_app/screens/assistant_tool_router.dart';
import 'package:nihaisha_app/screens/local_ai_interview_screen.dart';
import 'package:nihaisha_app/screens/meihua_screen.dart';
import 'package:nihaisha_app/services/ai_context_prompt_builder.dart';
import 'package:nihaisha_app/services/ai_context_resolver.dart';
import 'package:nihaisha_app/services/ai_tool_result_snapshot.dart';
import 'package:nihaisha_app/services/meihua_tool_executor.dart';
import 'package:nihaisha_app/theme/app_colors.dart';
import 'package:nihaisha_app/widgets/contextual_ai_sheet.dart';

import 'support/in_memory_assistant_conversation_store.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  final fixedNow = DateTime(2026, 11, 18, 12);

  test('Meihua number, time and random methods create immutable result snapshots', () {
    final executions = [
      MeihuaToolExecutor.executeWithSnapshot(
        const {
          'method': 'number',
          'date': '2026-11-18',
          'first': '3',
          'second': '7',
        },
        now: fixedNow,
      ),
      MeihuaToolExecutor.executeWithSnapshot(
        const {
          'method': 'time',
          'date': '2026-11-18',
          'hour_branch': '午',
        },
        now: fixedNow,
      ),
      MeihuaToolExecutor.executeWithSnapshot(
        const {
          'method': 'random',
          'date': '2026-11-18',
        },
        now: fixedNow,
        rng: Random(42),
      ),
    ];

    expect(executions.every((execution) => execution.succeeded), isTrue);
    for (final execution in executions) {
      final snapshot = execution.structuredSnapshot!;
      final input = snapshot['input']! as Map<String, Object?>;
      final result = snapshot['result']! as Map<String, Object?>;
      final ref = AiContextResolver.buildMeihuaResultContextRef(
        structuredSnapshot: snapshot,
      );
      final resolved = AiContextResolver.resolveMeihuaToolResult(
        ref: ref,
        structuredSnapshot: snapshot,
      );

      expect(ref.kind, AiContextKind.toolResult);
      expect(ref.moduleId, 'meihua');
      expect(ref.snapshotId, hasLength(64));
      expect(ref.sourceId, MeihuaToolExecutor.sourceId);
      expect(resolved.isResolved, isTrue);
      expect(input['method'], result['method']);
      expect(result['main'], isA<Map<String, Object?>>());
      expect(result['mutual'], isA<Map<String, Object?>>());
      expect(result['changed'], isA<Map<String, Object?>>());
      expect(result['stages'], hasLength(3));
      expect(result['trace'], isNotEmpty);

      final prompt = AiContextPromptBuilder.buildMeihuaToolResult(
        resolvedResult: resolved.value!,
      );
      expect(prompt, contains('主卦'));
      expect(prompt, contains('互卦'));
      expect(prompt, contains('变卦'));
      expect(prompt, contains('体用关系'));
      expect(prompt, contains('不得重新随机'));
      expect(prompt, contains(ref.snapshotId!));
    }
  });

  test('Meihua random execution preserves the actual draw and legacy result API', () {
    const arguments = {
      'method': 'random',
      'date': '2026-11-18',
    };
    final execution = MeihuaToolExecutor.executeWithSnapshot(
      arguments,
      now: fixedNow,
      rng: Random(42),
    );
    final legacy = MeihuaToolExecutor.execute(
      arguments,
      now: fixedNow,
      rng: Random(42),
    );

    expect(execution.succeeded, isTrue);
    expect(legacy.values, execution.result.values);
    expect(
      AiToolResultSnapshot.createStructuredId(
        snapshot: execution.structuredSnapshot!,
      ),
      execution.structuredSnapshot!['snapshotId'],
      reason: 'Opening AI consumes the exact snapshot generated by this execution.',
    );
    final trace = (execution.structuredSnapshot!['result']
        as Map<String, Object?>)['trace'] as List;
    expect(trace.join(' '), contains('随机'));
  });

  test('Meihua resolver rejects stale, tampered and mismatched snapshots', () {
    final execution = MeihuaToolExecutor.executeWithSnapshot(
      const {
        'method': 'number',
        'date': '2026-11-18',
        'first': '3',
        'second': '7',
      },
      now: fixedNow,
    );
    final snapshot = execution.structuredSnapshot!;
    final ref = AiContextResolver.buildMeihuaResultContextRef(
      structuredSnapshot: snapshot,
    );

    final staleRule = AiContextRef(
      kind: AiContextKind.toolResult,
      moduleId: ref.moduleId,
      anchorId: ref.anchorId,
      anchorVersion: ref.anchorVersion,
      snapshotId: ref.snapshotId,
      ruleVersion: 'meihua-engine@STALE',
      sourceId: ref.sourceId,
      title: ref.title,
    );
    expect(
      AiContextResolver.resolveMeihuaToolResult(
        ref: staleRule,
        structuredSnapshot: snapshot,
      ).status,
      AiContextResolutionStatus.stale,
    );

    final wrongSource = AiContextRef(
      kind: AiContextKind.toolResult,
      moduleId: ref.moduleId,
      anchorId: ref.anchorId,
      anchorVersion: ref.anchorVersion,
      snapshotId: ref.snapshotId,
      ruleVersion: ref.ruleVersion,
      sourceId: 'unverified:meihua',
      title: ref.title,
    );
    expect(
      AiContextResolver.resolveMeihuaToolResult(
        ref: wrongSource,
        structuredSnapshot: snapshot,
      ).status,
      AiContextResolutionStatus.unknown,
    );

    final tampered = Map<String, Object?>.from(snapshot);
    final tamperedResult = Map<String, Object?>.from(
      snapshot['result']! as Map<String, Object?>,
    )..['verdict'] = 'tampered';
    tampered['result'] = tamperedResult;
    expect(
      AiContextResolver.resolveMeihuaToolResult(
        ref: ref,
        structuredSnapshot: tampered,
      ).status,
      AiContextResolutionStatus.stale,
    );
    expect(
      () => AiContextPromptBuilder.buildToolResult(
        ref: ref,
        structuredSnapshot: tampered,
      ),
      throwsArgumentError,
    );

    final invalidDateExecution = MeihuaToolExecutor.executeWithSnapshot(
      const {
        'method': 'number',
        'date': '2026-99-99',
        'first': '3',
        'second': '7',
      },
      now: fixedNow,
    );
    expect(invalidDateExecution.succeeded, isFalse);
    expect(invalidDateExecution.result.status, AssistantToolExecutionStatus.failed);
  });

  testWidgets(
    'Meihua screen opens explanation-only metaphysics AI with the exact current result snapshot',
    (tester) async {
      tester.view.devicePixelRatio = 1;
      tester.view.physicalSize = const Size(1080, 3200);
      addTearDown(tester.view.reset);

      await tester.pumpWidget(
        ContextualAiConversationStoreScope(
          conversationStore: InMemoryAssistantConversationStore(),
          child: MaterialApp(
            theme: ThemeData(
              useMaterial3: true,
              colorScheme: AppColors.colorSchemeFor(Brightness.light),
              extensions: [AppColors.light],
            ),
            home: MeihuaScreen(
              accelSource: ({
                Duration samplingPeriod = Duration.zero,
              }) =>
                  const Stream<AccelerometerEvent>.empty(),
            ),
          ),
        ),
      );
      await tester.pumpAndSettle();

      final ask = find.text('问 AI 解读当前梅花易数结果');
      expect(ask, findsOneWidget);
      await tester.tap(ask);
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 500));

      final assistant = find.byType(LocalAiInterviewScreen);
      expect(assistant, findsOneWidget);
      final widget = tester.widget<LocalAiInterviewScreen>(assistant);
      expect(widget.initialMode, AssistantMode.metaphysics);
      expect(widget.contextualExplanationOnly, isTrue);
      expect(widget.contextRef['kind'], 'toolResult');
      expect(widget.contextRef['moduleId'], 'meihua');
      expect(widget.contextRef['snapshotId'], hasLength(64));
      expect(widget.initialPrompt, contains('梅花易数'));
      expect(widget.initialPrompt, contains('主卦'));
      expect(widget.initialPrompt, contains('不得重新随机'));
      expect(tester.takeException(), isNull);
    },
  );
}
